/**
 * Mengacak urutan opsi pilihan jawaban (A, B, C, D) dengan algoritma Fisher-Yates,
 * sekaligus mengupdate correctIndex secara presisi agar selalu mencocokkan jawaban yang benar.
 */
export function shuffleQuestionOptions(question) {
  const originalOptions = question.options;
  const correctText = originalOptions[question.correctIndex];

  const optionsWithFlag = originalOptions.map((opt, idx) => ({
    text: opt,
    isCorrect: idx === question.correctIndex
  }));

  // Fisher-Yates Shuffle
  for (let i = optionsWithFlag.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [optionsWithFlag[i], optionsWithFlag[j]] = [optionsWithFlag[j], optionsWithFlag[i]];
  }

  const shuffledOptions = optionsWithFlag.map(o => o.text);
  const newCorrectIndex = optionsWithFlag.findIndex(o => o.isCorrect);

  return {
    ...question,
    options: shuffledOptions,
    correctIndex: newCorrectIndex,
    correctText: correctText
  };
}

/**
 * Mengambil soal acak yang belum pernah ditanyakan, dan langsung mengacak opsi pilihannya.
 */
export function getRandomQuestion(excludeIds = []) {
  const available = questionsBank.filter(q => !excludeIds.includes(q.id));
  const pool = available.length > 0 ? available : questionsBank;
  const randomIndex = Math.floor(Math.random() * pool.length);
  const rawQuestion = pool[randomIndex];

  return shuffleQuestionOptions(rawQuestion);
}
